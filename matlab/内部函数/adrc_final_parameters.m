function p = adrc_final_parameters
% 第26～30讲共享的教学配置，绝不是公共C++库的机器人默认参数。
p=struct('b0',40,'wo',20,'wc',8,'h',0.001,'alpha1',0.5,'alpha2',0.25, ...
    'delta',0.01,'feedback_alpha1',0.75,'feedback_alpha2',1.5,'feedback_delta',0.1, ...
    'td_r',20,'td_h0',0.01,'limit',0.3,'sigma',0.001,'seed',20261028);
p.linear_beta=[3*p.wo,3*p.wo^2,p.wo^3];
% 匹配零点附近有效增益；不是把非线性beta直接叫作同带宽。
p.eso=[p.b0,p.linear_beta(1),p.linear_beta(2)*p.delta^(1-p.alpha1), ...
    p.linear_beta(3)*p.delta^(1-p.alpha2),p.alpha1,p.alpha2,p.delta];
p.feedback=[p.b0,p.wc^2*p.feedback_delta^(1-p.feedback_alpha1),p.feedback_alpha1, ...
    2*p.wc*p.feedback_delta^(1-p.feedback_alpha2),p.feedback_alpha2,p.feedback_delta];
end
